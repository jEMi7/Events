# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases

database_url = os.environ.get('DATABASE_URL', '').strip()
if not database_url:
    raise ImproperlyConfigured('Set DATABASE_URL in backend/.env or the environment.')

if not database_url.lower().startswith(('postgres://', 'postgresql://')):
    raise ImproperlyConfigured('DATABASE_URL must be a PostgreSQL connection URL.')

try:
    database_config = dj_database_url.parse(
        database_url,
        conn_max_age=0,
        conn_health_checks=True,
        disable_server_side_cursors=True,
    )
except (dj_database_url.ParseError, dj_database_url.UnknownSchemeError, ValueError, TypeError):
    # Never include the URL (and its password) in a configuration error.
    raise ImproperlyConfigured('DATABASE_URL is not a valid PostgreSQL connection URL.') from None

if not database_config.get('HOST') or not database_config.get('NAME'):
    raise ImproperlyConfigured('DATABASE_URL must specify a host and an existing database name.')

database_options = database_config.setdefault('OPTIONS', {})
# Enforce TLS while preserving stronger certificate verification from the URL.
if database_options.get('sslmode') not in ('require', 'verify-ca', 'verify-full'):
    database_options['sslmode'] = 'require'
database_options.setdefault('connect_timeout', 15)

DATABASES = {'default': database_config}
del database_url


